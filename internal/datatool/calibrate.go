package datatool

import (
	"cmp"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"slices"
	"strings"

	"github.com/thorstenpfister/basho/internal/derive"
	"github.com/thorstenpfister/basho/internal/domain"
	"github.com/thorstenpfister/basho/internal/rating"
	"github.com/thorstenpfister/basho/internal/snapshot"
)

// Calibration is the outcome of a grid search (SPEC §6.8).
type Calibration struct {
	Split     rating.Split
	Results   []rating.Result // best first
	Baselines rating.Baselines
	Peaks     []Peak // the chosen parameters' highest ratings, for the plausibility check
}

// Peak is a wrestler's highest rating at the end of a tournament.
type Peak struct {
	ID     domain.RikishiID
	Name   string
	Rating float64
	Basho  domain.BashoID
}

// Best returns the chosen parameters' result.
func (c Calibration) Best() rating.Result { return c.Results[0] }

// Shown reports V9: the rating beats the rank baseline on evaluation log loss.
func (c Calibration) Shown() bool { return c.Best().Eval.LogLoss < c.Baselines.Rank.Eval.LogLoss }

// History is the snapshot as calibration reads it.
type History struct {
	Tournaments [][]domain.Bout // oldest first, each in order of play
	Through     domain.BashoID
	Names       map[domain.RikishiID]string
}

// LoadHistory reads the snapshot in fsys.
func LoadHistory(fsys fs.FS) (History, error) {
	s, err := snapshot.Open(fsys)
	if err != nil {
		return History{}, err
	}
	x, err := s.BuildIndex()
	if err != nil {
		return History{}, err
	}
	rs, err := s.Rikishi()
	if err != nil {
		return History{}, err
	}
	h := History{Through: s.Manifest().Newest(), Names: make(map[domain.RikishiID]string, len(rs))}
	for _, r := range rs {
		h.Names[r.ID] = r.Name.En
	}
	for _, id := range x.Tournaments() {
		bouts := slices.Clone(x.Tournament(id))
		slices.SortStableFunc(bouts, derive.ComparePlay)
		h.Tournaments = append(h.Tournaments, bouts)
	}
	return h, nil
}

// Calibrate searches the grid over the history and lists the chosen
// parameters' 10 highest peaks.
func Calibrate(h History) Calibration {
	split := rating.DefaultSplit(h.Through)
	c := Calibration{
		Split:     split,
		Results:   rating.Calibrate(rating.Grid(), h.Tournaments, split),
		Baselines: rating.FitBaselines(h.Tournaments, split),
	}
	c.Peaks = PeakRatings(c.Best().Params, h, 10)
	return c
}

// PeakRatings returns the n wrestlers with the highest rating at the end of
// any tournament, each at their best, highest first.
func PeakRatings(p rating.Params, h History, n int) []Peak {
	r := rating.New(p)
	best := map[domain.RikishiID]Peak{}
	for _, bouts := range h.Tournaments {
		if len(bouts) == 0 {
			continue
		}
		id := bouts[0].Basho
		_ = r.Set(id, bouts) // oldest first
		for _, b := range bouts {
			for _, side := range []domain.BoutSide{b.East, b.West} {
				v, _ := r.Before(side.RikishiID, side.Rank, derive.EndOf(id))
				if v > best[side.RikishiID].Rating {
					best[side.RikishiID] = Peak{ID: side.RikishiID, Name: h.Names[side.RikishiID], Rating: v, Basho: id}
				}
			}
		}
	}
	peaks := slices.Collect(maps.Values(best))
	slices.SortFunc(peaks, func(a, b Peak) int { return cmp.Or(cmp.Compare(b.Rating, a.Rating), cmp.Compare(a.ID, b.ID)) })
	return peaks[:min(n, len(peaks))]
}

// ParamsFile is what goes into data/rating/params.json.
func (c Calibration) ParamsFile(generator string) rating.File {
	return rating.File{
		Schema: rating.FileSchema, Generator: generator,
		Params: c.Best().Params, Show: c.Shown(), Split: c.Split,
		Eval: c.Best().Eval, RankEval: c.Baselines.Rank.Eval, RankSlope: c.Baselines.RankSlope,
	}
}

// WriteReport writes docs/rating.md: the verdict, the top 5 parameter sets,
// both baselines and the calibration table.
func (c Calibration) WriteReport(w io.Writer) error {
	best, b := c.Best(), c.Baselines
	var sb strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&sb, format, args...) }
	verdict := "**shown**: the rating beats the rank baseline on log loss"
	if !c.Shown() {
		verdict = "**hidden**: the rating does not beat the rank baseline on log loss"
	}
	p("# Rating calibration\n\n")
	p("Generated by `basho-data rating calibrate` (SPEC §6.8, Appendix F) from the snapshot through %s. ", c.Split.Through)
	p("Parameters are chosen on the training years %s–%s and judged on the evaluation years from %s; ", c.Split.TrainFrom, c.Split.EvalFrom.Prev(), c.Split.EvalFrom)
	p("1960–64 are the warm-up and not scored. Fusen and draws are not rated.\n\n")
	p("**V9:** win chance %s (%.4f against %.4f).\n\n", verdict, best.Eval.LogLoss, b.Rank.Eval.LogLoss)

	p("## Evaluation (%s onwards, %d bouts)\n\n", c.Split.EvalFrom, best.Eval.Bouts)
	p("| Model | Log loss | Brier | Accuracy |\n|---|---|---|---|\n")
	row := func(name string, m rating.Metrics) {
		p("| %s | %.4f | %.4f | %.1f%% |\n", name, m.LogLoss, m.Brier, 100*m.Accuracy)
	}
	row("Elo (chosen)", best.Eval)
	row(fmt.Sprintf("Higher rank wins (logistic, %.4f per level)", b.RankSlope), b.Rank.Eval)
	row("Coin flip", b.Coin.Eval)

	p("\n## Top 5 parameter sets\n\n")
	p("| K | K_new | new bouts | r | warm-up scale | Train log loss | Eval log loss | Eval Brier | Eval accuracy |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range c.Results[:min(5, len(c.Results))] {
		q := r.Params
		p("| %g | %g | %d | %g | %g | %.4f | %.4f | %.4f | %.1f%% |\n", q.K, q.KNew, q.NewBouts, q.R, q.WarmupScale, r.Train.LogLoss, r.Eval.LogLoss, r.Eval.Brier, 100*r.Eval.Accuracy)
	}
	p("\nTraining baselines: rank %.4f, coin %.4f (%d bouts).\n", b.Rank.Train.LogLoss, b.Coin.Train.LogLoss, best.Train.Bouts)

	p("\n## Calibration of the chosen parameters (evaluation)\n\n")
	p("| Predicted (east) | Bouts | Mean predicted | Actual |\n|---|---|---|---|\n")
	for i, k := range best.Eval.Calibration {
		if k.Bouts > 0 {
			p("| %d–%d%% | %d | %.1f%% | %.1f%% |\n", 10*i, 10*i+10, k.Bouts, 100*k.Predicted, 100*k.Actual)
		}
	}
	if len(c.Peaks) > 0 {
		p("\n## Plausibility: highest ratings of all time\n\n")
		p("Each wrestler's highest rating at the end of a tournament, with the chosen parameters. ")
		p("For comparison, Ozeki Analytics' all-time Elo list (all divisions from 1958, K 20, through 2024) has Hakuho first.\n\n")
		p("| # | Wrestler | Peak | Tournament |\n|---|---|---|---|\n")
		for i, k := range c.Peaks {
			p("| %d | %s | %.0f | %s |\n", i+1, k.Name, k.Rating, k.Basho)
		}
	}
	_, err := io.WriteString(w, sb.String())
	return err
}
